"""Index completed evaluator and experiment receipts into a committed registry.

Scans ``runs/`` for top-level JSON receipts (skipping anything over a size cap,
journals, configs and non-receipt files), extracts the identity and summary
fields that a reader needs to find and trust a result, and writes:

- ``docs/results/registry.json``: one row per receipt, sorted by name
- ``docs/results/LADDER.md``: the same rows as a Markdown table

Game-level rows stay in ``runs/``; the registry is a map to evidence, not the
evidence. A row with ``pass`` says only that the receipt's own predeclared gate
passed. Promotion decisions live in the research record.

Usage: uv run python scripts/build_results_registry.py [--runs runs] [--max-bytes N]
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys


def receipt_row(path, data):
    config = data.get('config') or {}
    summary = data.get('summary')
    row = {'name': path.stem, 'path': str(path), 'bytes': path.stat().st_size,
           'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
           'kind': 'search_eval' if 'games' in data and 'summary' in data else 'experiment' if 'aggregate' in data or 'results' in data else 'other',
           'stage': config.get('stage'), 'candidate': config.get('candidate'), 'control': config.get('control'),
           'host': data.get('host'), 'process_cap': data.get('process_cap'),
           'source_revision': data.get('source_revision'),
           'source_hash': hashlib.sha256(json.dumps(data.get('source'), sort_keys=True).encode()).hexdigest()[:16] if data.get('source') else None,
           'checkpoint_sha256': (data.get('checkpoint') or {}).get('sha256'),
           'games': len(data['games']) * 2 if isinstance(data.get('games'), list) else None,
           'pass': None, 'panels': {}}
    if isinstance(summary, dict) and 'panels' in summary:
        row['pass'] = summary.get('pass')
        for name, panel in summary['panels'].items():
            if not isinstance(panel, dict):
                continue
            row['panels'][name] = {k: panel.get(k) for k in ('pairs', 'paired_win_lift', 'paired_seed_lcb', 'match_truncations',
                                                             'external_faults', 'p95_seconds', 'cluster_sd',
                                                             'minimum_detectable_effect_80', 'pass') if k in panel}
    elif isinstance(summary, dict):
        row['pass'] = summary.get('pass')
        row['panels']['summary'] = {k: v for k, v in summary.items() if not isinstance(v, (dict, list))}
    return row


def render_markdown(rows):
    lines = ['# Results ladder', '',
             'Generated by `scripts/build_results_registry.py` from receipts under `runs/`. Do not hand-edit.',
             'Each row is one receipt; `pass` is that receipt\'s own predeclared gate, not a promotion decision.',
             'Lift is paired candidate-minus-control win rate per panel; `mde80` is the smallest true lift the',
             'panel design could detect at 80% power (present only for receipts written after the power tooling).', '',
             '| receipt | stage | candidate | control | panel | pairs | lift | lcb | faults | mde80 | pass |',
             '|---|---|---|---|---|---:|---:|---:|---:|---:|---|']
    for row in rows:
        panels = row['panels'] or {'': {}}
        for name, panel in panels.items():
            fmt = lambda v: '' if v is None else f'{v:+.3f}' if isinstance(v, float) else str(v)
            lines.append('| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |'.format(
                row['name'], row['stage'] or '', row['candidate'] or '', row['control'] or '', name,
                panel.get('pairs', ''), fmt(panel.get('paired_win_lift')), fmt(panel.get('paired_seed_lcb')),
                panel.get('external_faults', ''), fmt(panel.get('minimum_detectable_effect_80')),
                '' if panel.get('pass', row['pass']) is None else panel.get('pass', row['pass'])))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--runs', type=Path, default=Path('runs'))
    parser.add_argument('--out', type=Path, default=Path('docs/results'))
    parser.add_argument('--max-bytes', type=int, default=64_000_000)
    args = parser.parse_args()
    rows, skipped = [], []
    for path in sorted(args.runs.glob('*.json')):
        if path.name.endswith('.config.json') or path.stat().st_size > args.max_bytes:
            skipped.append({'path': str(path), 'bytes': path.stat().st_size, 'reason': 'config or over size cap'})
            continue
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError) as exc:
            skipped.append({'path': str(path), 'reason': f'unreadable: {exc}'})
            continue
        if not isinstance(data, dict):
            continue
        rows.append(receipt_row(path, data))
    for summary in sorted(args.runs.glob('*/summary.json')):
        try:
            data = json.loads(summary.read_text())
        except (OSError, ValueError):
            continue
        if isinstance(data, dict):
            row = receipt_row(summary, data if 'summary' in data else {'summary': data, 'config': data.get('config', {})})
            row['name'] = summary.parent.name
            rows.append(row)
    rows.sort(key=lambda r: r['name'])
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'registry.json').write_text(json.dumps({'schema': 1, 'receipts': rows, 'skipped': skipped}, indent=1, sort_keys=True))
    (args.out / 'LADDER.md').write_text(render_markdown(rows))
    print(f'{len(rows)} receipts indexed, {len(skipped)} skipped -> {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
